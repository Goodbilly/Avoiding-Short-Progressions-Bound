from fractions import Fraction as F

def largest_gap(p, u, M, beta):
    points = sorted(
        (-u*k*k - beta*k) % p
        for k in range(M)
    )

    gaps = [
        points[i+1] - points[i]
        for i in range(M-1)
    ]
    gaps.append(p + points[0] - points[-1])

    return max(gaps)

def compute_G(p, M, u):
    best = F(0)

    # Check every coincidence of two points.
    for i in range(M):
        for j in range(i+1, M):
            for m in range(j-i):
                beta = F(p*m, j-i) - u*(i+j)
                gap = largest_gap(p, u, M, beta)
                best = max(best, gap)

    return best

p = 29
M = 22
u = F(1, 2)

print(compute_G(p, M, u))
